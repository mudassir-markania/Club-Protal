// Generates src/routes.generated.ts from the route modules in src/routes
// (src/routes/matches/[id]/declare-winner/route.ts  ->  /api/matches/:id/declare-winner).
// Run automatically before `dev` and `build`; re-run it after adding or removing a route file.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const routesDir = path.resolve(here, '../src/routes');
const outFile = path.resolve(here, '../src/routes.generated.ts');

const files = [];
(function walk(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full);
    else if (/^route\.(ts|js)$/.test(entry.name)) files.push(full);
  }
})(routesDir);

const toExpressPath = (file) => {
  const rel = path.relative(routesDir, path.dirname(file)).split(path.sep).filter(Boolean);
  return '/api' + (rel.length ? '/' + rel.map((seg) => seg.replace(/^\[(.+)\]$/, ':$1')).join('/') : '');
};

// Static segments must be registered before parameters (/players/import-csv before /players/:id)
const entries = files
  .map((f) => ({ file: f, route: toExpressPath(f) }))
  .sort((a, b) => {
    const sa = a.route.split('/');
    const sb = b.route.split('/');
    for (let i = 0; i < Math.max(sa.length, sb.length); i++) {
      const x = sa[i];
      const y = sb[i];
      if (x === y) continue;
      if (x === undefined) return -1;
      if (y === undefined) return 1;
      const px = x.startsWith(':');
      const py = y.startsWith(':');
      if (px !== py) return px ? 1 : -1;
      return x.localeCompare(y);
    }
    return 0;
  });

const lines = [
  '// AUTO-GENERATED by scripts/generate-routes.mjs - do not edit.',
  ...entries.map((e, i) => {
    const rel = './routes/' + path.relative(routesDir, e.file).split(path.sep).join('/').replace(/\.(ts|js)$/, '');
    return `import * as route${i} from '${rel}';`;
  }),
  '',
  'export const routes = [',
  ...entries.map((e, i) => `  { path: '${e.route}', module: route${i} as Record<string, unknown> },`),
  '];',
  '',
];
fs.writeFileSync(outFile, lines.join('\n'));
console.log(`Generated ${entries.length} routes -> src/routes.generated.ts`);
